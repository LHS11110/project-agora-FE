import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { createServer } from 'vite';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright-core');
const server = await createServer({ server: { host: '127.0.0.1', port: 0, https: false, open: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--enable-gpu', '--use-gl=angle', '--use-angle=gl-egl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1900, height: 800 } });
  if (process.env.FORCE_CPU) await page.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function (type, ...args) { return type === 'webgl' || type === 'webgl2' ? null : original.call(this, type, ...args); }; }); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/shape-appearance.html`);
  await page.waitForFunction(() => window.shapeState?.vertexCount === 6);
  const vertices = page.getByRole('spinbutton', { name: '꼭짓점 수', exact: true });
  await vertices.fill('7'); await vertices.press('Enter');
  await page.waitForFunction(() => window.shapeState.vertexCount === 7 && window.shapeState.contourPoints === 8);
  await page.getByRole('button', { name: '둥글게', exact: true }).click();
  await page.waitForFunction(() => window.shapeState.cornerStyle === 'rounded' && window.shapeState.contourPoints === 64);
  const transparency = page.getByRole('spinbutton', { name: '채우기 투명도', exact: true });
  await transparency.fill('50'); await transparency.press('Enter');
  await page.waitForFunction(() => window.shapeState.fillOpacity === .5);
  const alpha = () => page.locator('#direct-paint').evaluate(canvas => canvas.getContext('2d').getImageData(280, 240, 1, 1).data[3]);
  assert.ok(Math.abs(await alpha() - 128) <= 1, 'standard fill uses actual half alpha');
  await page.getByRole('button', { name: '손그림', exact: true }).click();
  await page.waitForFunction(() => window.shapeState.visualStyle === 'sketch');
  const ink = page.getByRole('spinbutton', { name: '빗금 진하기', exact: true });
  assert.equal(await ink.inputValue(), '80');
  const inkCoverage = () => page.locator('#direct-paint').evaluate(canvas => {
    const pixels = canvas.getContext('2d').getImageData(180, 160, 180, 150).data;
    let alpha = 0; for (let i = 3; i < pixels.length; i += 4) alpha += pixels[i]; return alpha;
  });
  await ink.fill('30'); await ink.press('Enter');
  await page.waitForFunction(() => window.shapeState.sketchFillOpacity === .3);
  const lightCoverage = await inkCoverage();
  const lineCount = await page.evaluate(() => window.shapeState.hatchCount);
  await ink.fill('100'); await ink.press('Enter');
  await page.waitForFunction(() => window.shapeState.sketchFillOpacity === 1);
  assert.equal(await page.evaluate(() => window.shapeState.hatchCount), lineCount, 'ink darkness keeps hatch density');
  assert.ok(await inkCoverage() > lightCoverage * 2.5, '100% ink paints materially darker pixels than 30%');
  const sparse = await page.evaluate(() => window.shapeState.hatchCount);
  await transparency.fill('0'); await transparency.press('Enter');
  await page.waitForFunction(() => window.shapeState.fillOpacity === 1);
  assert.ok(await page.evaluate(() => window.shapeState.hatchCount) > sparse * 1.8);
  await transparency.fill('100'); await transparency.press('Enter');
  await page.waitForFunction(() => window.shapeState.fillOpacity === 0);
  assert.equal(await alpha(), 0);
  assert.equal(await page.evaluate(() => window.shapeState.hatchCount), 0);
  await page.getByRole('switch', { name: '도형 내부 채우기', exact: true }).click();
  assert.equal(await transparency.count(), 0);
  await page.evaluate(() => window.patchShape({ shapeType: 'rectangle', strokeEnabled: false, fill: '#dd4422', fillOpacity: .5, cornerStyle: 'sharp', visualStyle: 'standard' }));
  await page.waitForFunction(() => document.querySelector('#renderer-stage .vector-layer')?.__agoraRenderStats?.visibleObjects === 1);
  const renderer = page.locator('#renderer-stage .vector-layer');
  await page.waitForFunction(() => ['webgl', 'canvas2d'].includes(document.querySelector('#renderer-stage .vector-layer')?.dataset.renderer));
  const mode = await renderer.getAttribute('data-renderer');
  assert.equal(mode, process.env.FORCE_CPU ? 'canvas2d' : 'webgl');
  await page.waitForTimeout(300);
  const screenshot = await page.locator('#renderer-stage').screenshot();
  const pixel = await page.evaluate(async bytes => {
    const bitmap = await createImageBitmap(new Blob([new Uint8Array(bytes)], { type: 'image/png' }));
    const canvas = document.createElement('canvas'); canvas.width = bitmap.width; canvas.height = bitmap.height;
    const ctx = canvas.getContext('2d'); ctx.drawImage(bitmap, 0, 0); bitmap.close();
    return [...ctx.getImageData(280, 240, 1, 1).data];
  }, [...screenshot]);
  for (const [index, expected] of [238, 162, 145].entries()) assert.ok(Math.abs(pixel[index] - expected) <= 2, `${mode} rectangle tint keeps half transparency: ${pixel}`);
  await page.evaluate(() => window.patchShape({ strokeEnabled: true, color: '#ff0000', fill: '', fillOpacity: 1 }));
  const borderWidth = page.getByRole('spinbutton', { name: '도형 테두리 굵기', exact: true });
  await borderWidth.fill('64'); await borderWidth.press('Enter');
  await page.waitForFunction(() => window.shapeState.strokeWidth === 64);
  await page.waitForTimeout(300);
  const borderPng = await page.locator('#renderer-stage').screenshot();
  const borderPixels = await page.evaluate(async bytes => {
    const bitmap = await createImageBitmap(new Blob([new Uint8Array(bytes)], { type: 'image/png' }));
    const canvas = document.createElement('canvas'); canvas.width = bitmap.width; canvas.height = bitmap.height;
    const ctx = canvas.getContext('2d'); ctx.drawImage(bitmap, 0, 0); bitmap.close();
    return [49, 79, 110, 449, 479, 510].map(x => [...ctx.getImageData(x, 240, 1, 1).data]);
  }, [...borderPng]);
  assert.ok(borderPixels.every(p => p[0] > 240 && p[1] < 15 && p[2] < 15), `${mode} 64px border must remain unclipped: ${JSON.stringify(borderPixels)}`);
  assert.deepEqual(errors, []);
  console.log('Polygon count, rounded corners, actual fill alpha and sketch density border width and sketch ink darkness controls passed in Chrome.');
} finally { await browser?.close(); await server.close(); }
